#!/bin/bash
# Writes db/pending.sql: every migration newer than the dump's marker, in order.
# sqlc and the test databases read it after schema.sql, so a PR's new migration is
# usable before it reaches staging; after the next db:schema it is empty again.
set -euo pipefail
cd "$(dirname "$0")/.."

through=$(sed -n '1s/^-- migrations through: //p' db/schema.sql)
: "${through:?db/schema.sql has no '-- migrations through:' marker; rerun pnpm db:schema}"

{
    echo "-- Generated by scripts/pending.sh from supabase/migrations newer than $through. Do not edit."
    for f in ../supabase/migrations/*.sql; do
        version=$(basename "$f" | cut -d_ -f1)
        if [[ "$version" > "$through" ]]; then
            echo
            echo "-- $(basename "$f")"
            cat "$f"
        fi
    done
} >db/pending.sql
